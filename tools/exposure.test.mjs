// Exposure metric as CI (arXiv:2609.36373 §B.2, made executable).
//   node --test tools/exposure.test.mjs
//
// The paper's definition, borrowed as-is:
//   unit       = one actually-assembled context (here: one injected memory block)
//   forbidden  = an item is present AND its audience excludes a current viewer
//   counting   = per CONTEXT, not per item — ≥1 forbidden item makes the whole
//                context count as exposed
//   reporting  = exposure_rate = exposed contexts / total contexts, and always
//                report the denominator N, otherwise "0" carries no information
//
// Audience here = `scope`; viewer = the session's workspace. What we must NOT do is
// borrow the paper's 82%: that number is generated by their synthetic corpus at dose
// d=8. Our number has to be measured on our own fixture. What transfers is the
// definition — and this file is that transfer.
//
// Every isolation test is worthless if it cannot fail, so §3 is a deliberate
// negative control: it proves the detector sees the foreign record.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { VaultIndex } from '../plugin/lib/vault/index.js'
import { search } from '../plugin/lib/vault/query.js'
import plugin from '../plugin/lib/index.js'
import { writeMarker } from '../plugin/lib/workspace.js'

const SIDE_A = 'A-SIDE-可见'
const SIDE_B = 'B-SECRET-不可见'

const humanMessage = (id, text) => ({ id, role: 'user', content: [{ type: 'text', text }], source: { kind: 'user' } })

function makeCtx() {
  const tools = []
  const hooks = new Map()
  return {
    tools,
    hooks,
    ctx: {
      systemPrompt: { section: () => () => {} },
      tools: { register: (t) => (tools.push(t), () => {}) },
      on: (event, handler) => {
        if (!hooks.has(event)) hooks.set(event, [])
        hooks.get(event).push(handler)
      },
      logger: { warn: (m) => console.log(`  [warn] ${m}`) }
    }
  }
}

async function fixture() {
  const base = await mkdtemp(join(tmpdir(), 'dsh-exposure-'))
  const vaultRoot = join(base, 'kb')
  const workspace = join(base, 'Lab')
  const cwd = join(workspace, 'p1')
  await mkdir(cwd, { recursive: true })

  const put = async (rel, body) => {
    const abs = join(vaultRoot, ...rel.split('/'))
    await mkdir(join(abs, '..'), { recursive: true })
    await writeFile(abs, body, 'utf8')
  }
  await put('positioning.md', '---\ntype: positioning\n---\n# 定位\n\n契约。\n')

  // Two workspaces, both with a record about the same subject. Only the first
  // should ever reach a session working inside ws_a.
  const record = (scope, marker) =>
    `---\ntype: memory\nscope: ${scope}\nreview:\n  state: approved\norigin:\n  session: s\n  family: fam_${scope}\ncreated: 2026-10-23T10:00:00Z\n---\n# ${scope} 的记录\n\n并发丢事件的结论：${marker}\n`
  await put('workspaces/ws_a/memory/2026-10-23-a.md', record('ws_a', SIDE_A))
  await put('workspaces/ws_b/memory/2026-10-23-b.md', record('ws_b', SIDE_B))

  await writeMarker(workspace, {
    schema: 1,
    enabled: true,
    id: 'ws_a',
    episode: 'ep_a',
    coordinators: ['sess_coord'],
    state: 'active',
    lastActivity: new Date().toISOString()
  })

  const harness = makeCtx()
  plugin.apply(harness.ctx, { vaultRoot, fullStatIntervalMs: 0 })
  return { base, vaultRoot, workspace, cwd, harness, byName: new Map(harness.tools.map((t) => [t.name, t])) }
}

const asWorker = (cwd) => ({ workingDirectory: cwd, session: { id: 'sess_worker' } })

/** Assemble one injection block — this is our "exact assembled context". */
async function assembleContext(harness, agent, step) {
  const hook = harness.hooks.get('agent/pre-step')[0]
  const decision = { kind: 'continue', messages: [humanMessage(`m${step}`, '并发 丢事件 结论')] }
  const out = await hook({ agent, messages: decision.messages, step, signal: {} }, async () => decision)
  return out.messages[out.messages.length - 1].content[0].text
}

// ------------------------------------------------------- 1. isolation (the claim)

test('exposure: injected contexts contain zero foreign-workspace records (0/N)', async () => {
  const { base, cwd, harness } = await fixture()
  try {
    const agent = asWorker(cwd)
    const contexts = []
    for (let step = 1; step <= 3; step++) contexts.push(await assembleContext(harness, agent, step))

    const exposed = contexts.filter((block) => block.includes(SIDE_B))
    // The paper's reporting rule: always state the denominator, or "0" means nothing.
    assert.equal(
      exposed.length,
      0,
      `exposure_rate = ${exposed.length}/${contexts.length}，应为 0/${contexts.length}；泄漏内容出现在第 ${
        contexts.findIndex((b) => b.includes(SIDE_B)) + 1
      } 个上下文`
    )

    // And the isolation must not be achieved by injecting nothing at all.
    assert.ok(
      contexts.every((block) => block.includes(SIDE_A)),
      '本工作区自己的记录必须出现，否则"零暴露"是靠不干活换来的'
    )
  } finally {
    await rm(base, { recursive: true, force: true })
  }
})

// ------------------------------------------- 2. the detector must be able to fail

test('exposure: the foreign record exists and is findable, so its absence above is scope', async () => {
  const { base, vaultRoot, cwd, harness } = await fixture()
  try {
    // A raw index-level search finds it. If this failed, the isolation test above
    // would be vacuous — "not found" because the record is broken, not because it
    // was withheld.
    const index = new VaultIndex(vaultRoot)
    await index.rebuild()
    const raw = search(index, 'B-SECRET')
    assert.ok(raw.hits.length > 0, '对照记录必须在库里、且可被检索到')
    assert.ok(raw.hits.some((h) => h.path.includes('ws_b')), JSON.stringify(raw.hits.map((h) => h.path)))

    // ...but assembling a context for ws_a still excludes it.
    const block = await assembleContext(harness, asWorker(cwd), 1)
    assert.ok(!block.includes(SIDE_B), '检索引擎找得到 ≠ 可以进上下文')
  } finally {
    await rm(base, { recursive: true, force: true })
  }
})

// ------------------------------------- 3. the tool path is closed by default too

test('exposure: memory_search withholds foreign memory unless asked for it', async () => {
  const { base, cwd, byName } = await fixture()
  try {
    const agent = asWorker(cwd)

    const unscoped = await byName.get('memory_search').execute({ query: '并发 丢事件' }, { agent })
    assert.ok(unscoped.includes(SIDE_A), unscoped)
    assert.ok(!unscoped.includes(SIDE_B), `默认作用域下不应出现外部记录：${unscoped}`)
    assert.ok(unscoped.includes('已排除') && unscoped.includes('其他工作区'), '必须如实报告排除了多少条')

    const widened = await byName.get('memory_search').execute({ query: '并发 丢事件', allScopes: true }, { agent })
    assert.ok(widened.includes(SIDE_B), `显式 allScopes 应可见：${widened}`)

    const explicit = await byName.get('memory_search').execute({ query: '并发 丢事件', scope: 'ws_b' }, { agent })
    assert.ok(explicit.includes(SIDE_B), `显式指定 scope 应可见：${explicit}`)
  } finally {
    await rm(base, { recursive: true, force: true })
  }
})

// ------------------------------- 4. KB stays reachable: only `memory` is withheld

test('exposure: knowledge-base notes are not scope-gated, only workspace memory is', async () => {
  const { base, vaultRoot, cwd, byName } = await fixture()
  try {
    // A project finding looked at from a different workspace: this MUST stay
    // searchable, otherwise scoping would silently amputate the knowledge base.
    await mkdir(join(vaultRoot, 'projects', 'cpa', 'findings'), { recursive: true })
    await writeFile(
      join(vaultRoot, 'projects', 'cpa', 'findings', '并发丢事件.md'),
      '---\ntype: finding\nstatus: active\nauthority: measured\n---\n# 并发丢事件\n\n并发到 8 时开始丢事件，KB-可见。\n',
      'utf8'
    )
    const agent = asWorker(cwd)
    // Prove the note is actually indexed BEFORE asserting on retrieval. Otherwise a
    // "not found" is ambiguous: did scope withhold it, or did the write never land?
    const diag = await byName.get('memory_diagnose').execute({}, { agent })
    const typeLine = diag.split('\n').find((line) => line.includes('库内类型')) ?? diag
    assert.ok(typeLine.includes('finding=1'), `KB 条目没有被索引：${typeLine}`)

    const out = await byName.get('memory_search').execute({ query: '并发 丢事件' }, { agent })
    // Assert on the path, not on marker text: the tool prints the best *sentence*,
    // and for this note that sentence is the heading — the marker lives in the next
    // sentence and never appears in the rendered output.
    assert.ok(out.includes('projects/cpa/findings/并发丢事件.md'), `知识库条目不应被作用域挡住：${out}`)
  } finally {
    await rm(base, { recursive: true, force: true })
  }
})
